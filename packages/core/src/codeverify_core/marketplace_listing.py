"""GitHub Marketplace & One-Click Install.

Provides GitHub Marketplace listing management, one-click installation,
automatic configuration generation, and free-tier metering for
seamless CodeVerify onboarding.

Features:
- GitHub Marketplace listing metadata and pricing tiers
- One-click install flow with automatic repo configuration
- Free-tier usage metering and enforcement
- GitHub Actions workflow template generation
- Installation analytics and tracking
"""

from __future__ import annotations

import hashlib
import secrets
import uuid
from collections import defaultdict
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any

import structlog

logger = structlog.get_logger()


class MarketplacePlan(str, Enum):
    """Pricing plans available on GitHub Marketplace."""

    FREE = "free"
    PRO = "pro"
    TEAM = "team"
    ENTERPRISE = "enterprise"


class InstallationStatus(str, Enum):
    """Status of a GitHub App installation."""

    PENDING = "pending"
    ACTIVE = "active"
    SUSPENDED = "suspended"
    UNINSTALLED = "uninstalled"


class OnboardingPhase(str, Enum):
    """Phases of the one-click install flow."""

    APP_INSTALLED = "app_installed"
    CONFIG_GENERATED = "config_generated"
    WORKFLOW_CREATED = "workflow_created"
    BASELINE_SCAN_QUEUED = "baseline_scan_queued"
    ONBOARDING_COMPLETE = "onboarding_complete"


class UsageMetric(str, Enum):
    """Tracked usage metrics for metering."""

    VERIFICATIONS = "verifications"
    AI_ANALYSES = "ai_analyses"
    PR_REVIEWS = "pr_reviews"
    API_CALLS = "api_calls"


